// yesAnswers : réponses acceptées comme « oui » dans chaque langue (« y » partout).
var yesAnswers = map[Lang][]string{
	English:    {"y", "yes"},
	French:     {"o", "oui", "y", "yes"},
	Arabic:     {"y", "yes", "نعم"},
	Portuguese: {"s", "sim", "y", "yes"},
}

// IsYes indique si la réponse vaut « oui » dans la langue en cours.
func IsYes(answer string) bool {
	for _, yes := range yesAnswers[current] {
		if answer == yes {
			return true
		}
	}

	return false
}
